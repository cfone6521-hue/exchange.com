import React, { useState } from 'react';
import { useWallet } from '../wallet/WalletContext';
import { Shield, ShieldCheck, AlertCircle, X, Key, CheckCircle, Lock, RefreshCw } from 'lucide-react';

interface Web3AuthModalProps {
  isOpen: boolean;
  onClose: () => void;
  lang: 'pt' | 'en';
}

export const Web3AuthModal: React.FC<Web3AuthModalProps> = ({ isOpen, onClose, lang }) => {
  const {
    wallet,
    loginWithWeb3,
    logoutWeb3,
    authSession,
    isAuthenticated,
    isAuthenticating,
    authError,
  } = useWallet();

  const [lastNonce, setLastNonce] = useState<string | null>(null);
  const [step, setStep] = useState<'idle' | 'requesting_nonce' | 'signing' | 'verifying' | 'success'>('idle');

  if (!isOpen) return null;

  const t = {
    pt: {
      title: 'Autenticação Criptográfica Web3',
      subtitle: 'Assine digitalmente um nonce único com sua carteira para validar sua identidade.',
      walletConnected: 'Carteira Conectada',
      notConnected: 'Conecte sua carteira primeiro para autenticar.',
      howItWorksTitle: 'Como funciona a segurança?',
      point1: 'Nonce Criptográfico Único: Gerado pelo backend com validade de 5 minutos.',
      point2: 'Proteção Anti-Replay: O nonce é consumido imediatamente na primeira validação e não pode ser reutilizado.',
      point3: 'Zero Taxas de Gas: A assinatura é off-chain (EIP-191). Nenhuma transação financeira é executada.',
      point4: 'Sem Frases-Semente: Suas chaves privadas nunca deixam seu dispositivo ou carteira.',
      btnSign: 'Assinar com Carteira',
      btnSigning: 'Aguardando Assinatura...',
      authenticatedTitle: 'Sessão Web3 Autenticada',
      authenticatedDesc: 'Sua assinatura foi verificada pelo backend com sucesso. Token de sessão ativo.',
      btnLogout: 'Encerrar Sessão',
      close: 'Fechar',
      role: 'Privilégio:',
      expires: 'Expira em:',
      sessionToken: 'ID de Sessão:',
    },
    en: {
      title: 'Web3 Cryptographic Authentication',
      subtitle: 'Digitally sign a unique nonce with your wallet to verify your identity.',
      walletConnected: 'Connected Wallet',
      notConnected: 'Connect your wallet first to authenticate.',
      howItWorksTitle: 'Security Architecture',
      point1: 'Unique Cryptographic Nonce: Generated by backend with a 5-minute expiration.',
      point2: 'Replay Attack Protection: The nonce is consumed on first verification and cannot be reused.',
      point3: 'Zero Gas Fees: Signature is off-chain (EIP-191). No financial transaction is sent.',
      point4: 'No Seed Phrases: Your private keys never leave your secure wallet provider.',
      btnSign: 'Sign with Wallet',
      btnSigning: 'Awaiting Signature...',
      authenticatedTitle: 'Web3 Session Authenticated',
      authenticatedDesc: 'Your cryptographic signature was verified by the backend. Session token is active.',
      btnLogout: 'Log Out',
      close: 'Close',
      role: 'Role:',
      expires: 'Expires at:',
      sessionToken: 'Session ID:',
    },
  }[lang];

  const handleStartAuth = async () => {
    setStep('signing');
    const success = await loginWithWeb3();
    if (success) {
      setStep('success');
    } else {
      setStep('idle');
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-sm p-4">
      <div className="relative w-full max-w-lg rounded-2xl border border-slate-800 bg-[#0c121e] p-6 shadow-2xl shadow-cyan-950/40">
        {/* Close Button */}
        <button
          onClick={onClose}
          className="absolute right-4 top-4 rounded-lg p-1 text-slate-400 hover:bg-slate-800 hover:text-white transition-colors"
        >
          <X className="h-5 w-5" />
        </button>

        {/* Modal Header */}
        <div className="flex items-center gap-3 mb-5">
          <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-cyan-500/10 text-cyan-400 border border-cyan-500/20">
            <Lock className="h-5 w-5" />
          </div>
          <div>
            <h3 className="font-['Outfit'] text-base font-bold text-white">{t.title}</h3>
            <p className="text-xs text-slate-400">{t.subtitle}</p>
          </div>
        </div>

        {/* Current State */}
        {isAuthenticated && authSession ? (
          <div className="space-y-4">
            <div className="rounded-xl border border-emerald-500/20 bg-emerald-500/10 p-4">
              <div className="flex items-center gap-2.5 text-emerald-400">
                <CheckCircle className="h-5 w-5 shrink-0" />
                <span className="text-sm font-semibold">{t.authenticatedTitle}</span>
              </div>
              <p className="mt-1 text-xs text-emerald-300/80">{t.authenticatedDesc}</p>

              <div className="mt-3 space-y-1.5 pt-3 border-t border-emerald-500/20 text-xs">
                <div className="flex justify-between text-slate-400">
                  <span>{t.walletConnected}:</span>
                  <span className="font-mono text-slate-200">{authSession.address.substring(0, 8)}...{authSession.address.substring(36)}</span>
                </div>
                <div className="flex justify-between text-slate-400">
                  <span>{t.role}</span>
                  <span className="font-mono uppercase text-cyan-400 font-semibold">{authSession.role}</span>
                </div>
                <div className="flex justify-between text-slate-400">
                  <span>{t.expires}</span>
                  <span className="font-mono text-slate-300">{new Date(authSession.expiresAt).toLocaleTimeString()}</span>
                </div>
              </div>
            </div>

            <div className="flex gap-3">
              <button
                onClick={logoutWeb3}
                className="flex-1 rounded-xl border border-rose-500/30 bg-rose-500/10 py-2.5 text-xs font-semibold text-rose-400 hover:bg-rose-500/20 transition-colors"
              >
                {t.btnLogout}
              </button>
              <button
                onClick={onClose}
                className="flex-1 rounded-xl bg-slate-800 py-2.5 text-xs font-semibold text-white hover:bg-slate-700 transition-colors"
              >
                {t.close}
              </button>
            </div>
          </div>
        ) : (
          <div className="space-y-4">
            {/* Wallet status banner */}
            <div className="rounded-xl border border-slate-800 bg-slate-900/60 p-3 text-xs">
              <div className="text-slate-400">{t.walletConnected}:</div>
              {wallet.address ? (
                <div className="mt-1 font-mono text-cyan-400 break-all">{wallet.address}</div>
              ) : (
                <div className="mt-1 text-amber-400">{t.notConnected}</div>
              )}
            </div>

            {/* Security Explanation Cards */}
            <div className="rounded-xl border border-slate-800/80 bg-slate-900/40 p-4 space-y-2.5">
              <div className="text-xs font-semibold text-slate-300 flex items-center gap-1.5">
                <Shield className="h-4 w-4 text-cyan-400" />
                <span>{t.howItWorksTitle}</span>
              </div>
              <ul className="space-y-2 text-xs text-slate-400">
                <li className="flex items-start gap-2">
                  <span className="h-1.5 w-1.5 rounded-full bg-cyan-400 mt-1.5 shrink-0" />
                  <span>{t.point1}</span>
                </li>
                <li className="flex items-start gap-2">
                  <span className="h-1.5 w-1.5 rounded-full bg-cyan-400 mt-1.5 shrink-0" />
                  <span>{t.point2}</span>
                </li>
                <li className="flex items-start gap-2">
                  <span className="h-1.5 w-1.5 rounded-full bg-cyan-400 mt-1.5 shrink-0" />
                  <span>{t.point3}</span>
                </li>
                <li className="flex items-start gap-2">
                  <span className="h-1.5 w-1.5 rounded-full bg-cyan-400 mt-1.5 shrink-0" />
                  <span>{t.point4}</span>
                </li>
              </ul>
            </div>

            {/* Error Banner */}
            {authError && (
              <div className="rounded-xl border border-rose-500/20 bg-rose-500/10 p-3 text-xs text-rose-300 flex items-center gap-2">
                <AlertCircle className="h-4 w-4 shrink-0 text-rose-400" />
                <span>{authError}</span>
              </div>
            )}

            {/* Action Buttons */}
            <div className="pt-2">
              <button
                onClick={handleStartAuth}
                disabled={!wallet.isConnected || isAuthenticating}
                className="flex w-full items-center justify-center gap-2 rounded-xl bg-cyan-500 py-3 text-sm font-semibold text-slate-950 shadow-md shadow-cyan-500/25 hover:bg-cyan-400 active:scale-[0.99] disabled:opacity-50 disabled:cursor-not-allowed transition-all"
              >
                {isAuthenticating ? (
                  <>
                    <RefreshCw className="h-4 w-4 animate-spin" />
                    <span>{t.btnSigning}</span>
                  </>
                ) : (
                  <>
                    <Key className="h-4 w-4" />
                    <span>{t.btnSign}</span>
                  </>
                )}
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
